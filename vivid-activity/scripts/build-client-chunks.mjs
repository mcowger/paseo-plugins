import { build, transform } from "esbuild";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// The installed UI is served from server/generated, not rebuilt by `paseo plugin reload`.
const root = dirname(dirname(fileURLToPath(import.meta.url)));
const check = process.argv.includes("--check");
const hostModules = [
  "@getpaseo/plugin", "@getpaseo/plugin/server", "@getpaseo/plugin/server/provider", "@getpaseo/plugin/server/acp",
  "@getpaseo/plugin/client", "@getpaseo/plugin/client/ui", "@getpaseo/plugin/client/react-native",
  "@tanstack/react-query", "react", "react/jsx-runtime", "react-native", "zod",
];
const chunks = JSON.parse(await readFile(join(root, "client-chunks.json"), "utf8"));
for (const { name, entry, manifest, api } of chunks) {
  const result = await build({
    absWorkingDir: root, entryPoints: [entry], bundle: true, write: false, platform: "neutral", format: "cjs",
    target: "es2020", jsx: "automatic", external: hostModules, mainFields: ["module", "main"], loader: { ".svg": "text" },
    supported: { "async-await": false }, treeShaking: true,
    legalComments: "none", logLevel: "warning",
    plugins: [{ name: "client-boundary", setup(builder) {
      builder.onResolve({ filter: /^(?:node:)|(?:^|\/)server\// }, args => ({ errors: [{ text: `Server-only import in client chunk: ${args.path}` }] }));
    } }],
  });
  // The chunk is evaluated as source on phones, outside Metro. Match Paseo's Hermes
  // lowering and eager host-module interop before compacting the generated text.
  const output = result.outputFiles[0].text.replaceAll("get: () => from[key]", "value: from[key]");
  const compact = await transform(output, {
    loader: "js", format: "cjs", target: "es2020", supported: { "async-await": false },
    minifyWhitespace: true, minifySyntax: true, minifyIdentifiers: false, legalComments: "none",
  });
  const code = `(function(require) {\nconst module = { exports: {} };\nconst exports = module.exports;\n${compact.code}\nreturn module.exports;\n})`;
  const metadata = { name, hash: createHash("sha256").update(code).digest("hex").slice(0, 16), api, bytes: Buffer.byteLength(code) };
  for (const [path, content] of [
    [join(root, "server", "generated", `${name}-chunk.txt`), code],
    [join(root, "shared", "generated", `${name}-chunk-manifest.ts`),
      `// Generated by scripts/build-client-chunks.mjs; do not edit.\nexport const ${manifest} = ${JSON.stringify(metadata)} as const;\n`],
  ]) {
    if (check) {
      if (await readFile(path, "utf8") !== content) throw new Error(`${path} is stale; run npm run build:chunks`);
    } else await writeFile(path, content);
  }
  console.log(`${check ? "Verified" : "Built"} ${name}: ${metadata.bytes} bytes (${metadata.hash})`);
}
