#!/usr/bin/env node
/**
 * Builds the plugin's client payload and the two generated modules that carry it.
 *
 * Paseo compiles `index.client.tsx` itself, but it does so without minification
 * and it re-sends that output on every connect. So the real client code is built
 * here instead: minified, with the daemon's exact compile options, and handed to
 * the loader over an RPC (`server/payload.ts`) so a reconnect re-sends ~1 KB.
 *
 * The options below must stay in step with `compileTarget` in Paseo's
 * `packages/server/src/server/plugins/compiler.ts`: a mismatch shows up as a
 * Hermes evaluation failure on a device, not as a build error.
 *
 * Runs directly on Node's type stripping (`node scripts/build-client.ts`); no
 * build tool for the build tool.
 */
import { hash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import * as esbuild from "esbuild";

const root = path.resolve(import.meta.dirname, "..");

/** Host modules Paseo provides to every client bundle; they must never be inlined. */
const EXTERNALS = [
  "@getpaseo/plugin",
  "@getpaseo/plugin/server",
  "@getpaseo/plugin/server/provider",
  "@getpaseo/plugin/server/acp",
  "@getpaseo/plugin/client",
  "@getpaseo/plugin/client/ui",
  "@getpaseo/plugin/client/react-native",
  "@tanstack/react-query",
  "react",
  "react/jsx-runtime",
  "react-native",
  "zod",
];

export interface ClientPayloadBuild {
  /** The wrapped, minified CJS factory Paseo's loader evaluates. */
  code: string;
  /** Bundle inputs, relative to the plugin root, for the boundary guard. */
  inputs: string[];
}

/** Mirrors Paseo's `wrapCommonJsBundle`. */
function wrapCommonJsBundle(code: string): string {
  return `(function(require) {\nconst module = { exports: {} };\nconst exports = module.exports;\n${code}\nreturn module.exports;\n})`;
}

/** Mirrors Paseo's `makeHermesInteropEager`: Hermes resolves esbuild's lazy getters to the last export. */
function makeHermesInteropEager(code: string): string {
  return code.replaceAll("get: () => from[key]", "value: from[key]");
}

/** Builds the payload exactly as the daemon would compile it, then minifies. */
export async function buildClientPayload(): Promise<ClientPayloadBuild> {
  const result = await esbuild.build({
    absWorkingDir: root,
    entryPoints: ["client/entry.tsx"],
    bundle: true,
    format: "cjs",
    jsx: "automatic",
    platform: "neutral",
    target: "es2020",
    supported: { "async-await": false },
    mainFields: ["module", "main"],
    external: EXTERNALS,
    minify: true,
    legalComments: "none",
    treeShaking: true,
    logLevel: "silent",
    metafile: true,
    write: false,
  });
  const output = result.outputFiles?.[0]?.text;
  if (!output) throw new Error("Client payload compilation produced no output");
  return {
    code: wrapCommonJsBundle(makeHermesInteropEager(output)),
    inputs: Object.keys(result.metafile.inputs),
  };
}

/**
 * The payload must stay inside the client boundary. Node built-ins already fail
 * to resolve under `platform: "neutral"`; this catches the plugin's own `server/`
 * modules, which the daemon's boundary plugin would otherwise police.
 */
export function assertClientBoundary(inputs: readonly string[]): void {
  const offenders = inputs.filter((input) => input.replaceAll("\\", "/").startsWith("server/"));
  if (offenders.length > 0) {
    throw new Error(`Client payload imports server-only modules: ${offenders.join(", ")}`);
  }
}

/** Hermes evaluates plugin bundles from a string, where unlowered classes are unsafe. */
export function assertNoClasses(code: string): void {
  const stripped = code.replace(/\/\*[\s\S]*?\*\/|\/\/.*$/gm, "");
  const match = stripped.match(/\bclass\s+[A-Za-z0-9_$]+|\bclass\s*\{|=\s*class\b/);
  if (match) throw new Error(`Client payload contains an ES6 class: ${match[0]}`);
}

export function payloadVersion(code: string): string {
  return hash("sha256", code, "hex").slice(0, 12);
}

type GeneratedModule = readonly [file: string, render: (version: string, code: string) => string];

const GENERATED: readonly GeneratedModule[] = [
  [
    "shared/client-payload-version.ts",
    (version) =>
      [
        "// Generated by scripts/build-client.ts — do not edit.",
        "//",
        "// The hash of the client payload in server/client-payload.generated.ts. The",
        "// loader embeds it, so a payload change changes the catalog entry and Paseo",
        "// re-evaluates the plugin instead of keeping the previous installation.",
        `export const CLIENT_PAYLOAD_VERSION = ${JSON.stringify(version)};`,
        "",
      ].join("\n"),
  ],
  [
    "server/client-payload.generated.ts",
    (_version, code) =>
      [
        "// Generated by scripts/build-client.ts — do not edit.",
        "//",
        "// The plugin's real client code, served to index.client.tsx over the",
        "// client.payload RPC. Kept in the server bundle because a plugin server module",
        "// is evaluated from a string and cannot resolve its own directory.",
        `export const CLIENT_PAYLOAD = ${JSON.stringify(code)};`,
        "",
      ].join("\n"),
  ],
];

/** Builds, checks, and writes the payload and its generated modules. */
export async function writeClientPayload(): Promise<{ version: string; bytes: number }> {
  const { code, inputs } = await buildClientPayload();
  assertClientBoundary(inputs);
  assertNoClasses(code);
  const version = payloadVersion(code);
  for (const [file, render] of GENERATED) {
    await writeFile(path.join(root, file), render(version, code), "utf8");
  }
  return { version, bytes: code.length };
}

/** Compares the generated modules against a fresh build; returns the drift, if any. */
export async function findClientPayloadDrift(): Promise<{ version: string; drift: string[] }> {
  const { code } = await buildClientPayload();
  const version = payloadVersion(code);
  const drift: string[] = [];
  for (const [file, render] of GENERATED) {
    const expected = render(version, code);
    const actual = await readFile(path.join(root, file), "utf8").catch(() => "");
    if (actual !== expected) drift.push(file);
  }
  return { version, drift };
}

if (process.argv[1] && path.resolve(process.argv[1]) === import.meta.filename) {
  const { version, bytes } = await writeClientPayload();
  console.log(`Client payload: ${(bytes / 1024).toFixed(1)} KB, version ${version}`);
}
